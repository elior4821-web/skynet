export const SUBJECTS = {
  science: { label: "מדעים", defaultGrade: "ה" },
  math: { label: "מתמטיקה", defaultGrade: "ה" },
  minecraft: { label: "Minecraft Education", defaultGrade: "ה" },
};

export const CONTENT_TYPES = {
  "lesson-plan": "מערך שיעור",
  presentation: "מצגת",
};

function subjectGuidance(subject) {
  if (subject === "minecraft") {
    return `זהו מערך שיעור בתוך משחק ה-Minecraft Education עצמו (המשחק הוא כלי ההוראה,
לא רק נושא לימודי). כלול: מטרות פדגוגיות, הכנות נדרשות במשחק (world/map, בילדים,
redstone וכו' אם רלוונטי), שלבי משחק מפורטים לתלמידים, אתגרים/משימות בתוך המשחק,
והתייחסות לניהול כיתה בסביבה הדיגיטלית.`;
  }
  return `התאם את התוכן לתלמידי כיתה ה' (גילאי 10-11), עם שפה בהירה, דוגמאות
מהחיים היומיום, ומגוון אמצעי הוראה (הדגמה, עבודה בקבוצות, תרגול עצמאי).`;
}

export function buildSystemPrompt() {
  return `אתה עוזר הוראה מומחה לבניית מערכי שיעור ומצגות עבור מורים בבתי ספר יסודיים
בישראל. אתה כותב בעברית תקנית וברורה, בפורמט מובנה עם כותרות, ומתאים תמיד את
התוכן לתחום הדעת ולשכבת הגיל שצוינו. אתה מקצועי, פדגוגי, ומדויק מבחינה תוכנית -
כולל מטרות למידה, מהלך שיעור מחולק לשלבי זמן, אמצעי הערכה, וחומרים נדרשים.

חשוב: התאם את התוכן, המושגים והמטרות לתכנית הלימודים הרשמית של משרד החינוך
הישראלי לשכבת הגיל והמקצוע הרלוונטיים (לדוגמה: תכנית הלימודים במתמטיקה ובמדעים
וטכנולוגיה ליסודי). ציין בקצרה, בסעיף נפרד בסוף התוכן, לאילו תכני ליבה/מדדים
בתכנית הלימודים השיעור מתייחס, כדי שהמורה יוכל לוודא התאמה.`;
}

export function buildUserPrompt({ subject, grade, topic, contentType, duration, notes, referenceContext }) {
  const subjectLabel = SUBJECTS[subject]?.label ?? subject;
  const typeLabel = CONTENT_TYPES[contentType] ?? contentType;
  const gradeText = grade || SUBJECTS[subject]?.defaultGrade || "ה";

  const sections =
    contentType === "presentation"
      ? `בנה תוכן למצגת בת 8-12 שקפים. הקפד בדיוק על הפורמט הבא לכל שקף, כדי
  שניתן יהיה להמיר אותו אוטומטית לקובץ מצגת:
  ## שקף <מספר>: <כותרת קצרה>
  - נקודה ראשונה
  - נקודה שנייה
  - ...
  (הערת מנחה למורה, אם יש)
  אין להוסיף טקסט מחוץ למבנה הזה.`
      : `בנה מערך שיעור מלא הכולל: (1) נושא ומטרות למידה, (2) חומרים ואמצעים
  נדרשים, (3) פתיחה/מוטיבציה, (4) גוף השיעור מחולק לשלבים עם זמן משוער לכל שלב,
  (5) סיכום והערכה, (6) הצעה למשימת המשך/שיעורי בית.`;

  return `צור ${typeLabel} בנושא "${topic}" עבור מקצוע ${subjectLabel}, כיתה ${gradeText}.
${duration ? `משך השיעור: ${duration} דקות.` : ""}
${subjectGuidance(subject)}

${sections}

${notes ? `הערות נוספות מהמורה: ${notes}` : ""}

${
  referenceContext
    ? `להלן קטעים מתוך חומר הלימוד הרשמי (ספר לימוד / תכנית לימודים) שהמורה העלה.
בסס את התוכן על החומר הזה במידת האפשר, ושמור על התאמה למונחים ולסדר הנושאים בו:
"""
${referenceContext}
"""`
    : ""
}

הצג את התוצאה בפורמט Markdown קריא, עם כותרות (##) לכל חלק.`;
}
